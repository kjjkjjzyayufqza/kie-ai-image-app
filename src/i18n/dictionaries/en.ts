/** Widen leaf string literals so other locales can satisfy the same shape. */
type DeepStringLeaves<T> = {
  [K in keyof T]: T[K] extends string
    ? string
    : T[K] extends object
      ? DeepStringLeaves<T[K]>
      : T[K];
};

